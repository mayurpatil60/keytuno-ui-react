import type {
  PrimitiveColorTokens,
  SemanticColorTokens,
} from "../contracts/theme-contract";

export function createSemanticColors(
  palette: PrimitiveColorTokens,
  overrides: Partial<SemanticColorTokens> = {},
): SemanticColorTokens {
  return {
    backgroundDefault: palette.white,
    backgroundSurface: palette.slate50,
    backgroundMuted: palette.slate100,
    backgroundHover: `color-mix(in srgb, ${palette.slate100} 84%, ${palette.white})`,
    backgroundSelected: `color-mix(in srgb, ${palette.blue600} 20%, ${palette.white})`,
    textPrimary: palette.slate900,
    textSecondary: palette.slate600,
    borderMuted: palette.slate300,
    borderStrong: `color-mix(in srgb, ${palette.slate500} 76%, ${palette.slate300})`,
    actionPrimaryBackground: palette.blue600,
    actionPrimaryForeground: palette.white,
    actionPrimarySoftBackground: `color-mix(in srgb, ${palette.blue600} 16%, ${palette.white})`,
    actionSuccessBackground: "#00a86b",
    actionSuccessForeground: palette.white,
    actionSuccessSoftBackground: "#dcfce7",
    actionWarningBackground: "#f59f00",
    actionWarningForeground: palette.slate900,
    actionWarningSoftBackground: "#fef3c7",
    actionAccentBackground: "#ff4fa3",
    actionAccentForeground: palette.white,
    actionAccentSoftBackground: "#fce7f3",
    actionDangerBackground: "#f04438",
    actionDangerForeground: palette.white,
    actionDangerSoftBackground: "#fee2e2",
    buttonDefaultBackground: palette.slate100,
    buttonDefaultForeground: palette.slate900,
    buttonDefaultBorder: palette.slate300,
    buttonPrimaryBackground: palette.blue600,
    buttonPrimaryForeground: palette.white,
    buttonSuccessBackground: "#16a34a",
    buttonSuccessForeground: palette.white,
    buttonWarningBackground: "#f59e0b",
    buttonWarningForeground: palette.slate900,
    buttonAccentBackground: "#d94694",
    buttonAccentForeground: palette.white,
    buttonDestructiveBackground: "#ef4444",
    buttonDestructiveForeground: palette.white,
    ...overrides,
  };
}
